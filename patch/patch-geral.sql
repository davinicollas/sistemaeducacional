-- ============================================================
-- FK DOCUMENTOS -> TIPOS DE DOCUMENTOS
-- PostgreSQL não permite ADD CONSTRAINT IF NOT EXISTS.
-- Por isso usamos DO $$.
-- ============================================================

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_documentos_params_tipos_documentos'
    ) THEN
        ALTER TABLE documentos
            ADD CONSTRAINT fk_documentos_params_tipos_documentos
            FOREIGN KEY (idTipo)
            REFERENCES params_tipos_documentos (id);
    END IF;
END
$$;

