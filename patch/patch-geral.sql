-- Administradores: acesso total
INSERT INTO role_permissions (
    role_id,
    permission_id,
    access
)
SELECT
    r.id,
    p.id,
    'full'
FROM roles r
CROSS JOIN permissions p
WHERE r.name = 'Administradores'
ON CONFLICT (role_id, permission_id)
DO UPDATE SET
    access = EXCLUDED.access;


-- Professores: alunos, notas e frequência
INSERT INTO role_permissions (
    role_id,
    permission_id,
    access
)
SELECT
    r.id,
    p.id,
    'full'
FROM roles r
JOIN permissions p
    ON p.name IN (
        'Ver alunos',
        'Notas',
        'Frequência'
    )
WHERE r.name = 'Professores'
ON CONFLICT (role_id, permission_id)
DO UPDATE SET
    access = EXCLUDED.access;


-- Alunos: notas e frequência somente visualização
INSERT INTO role_permissions (
    role_id,
    permission_id,
    access
)
SELECT
    r.id,
    p.id,
    'view'
FROM roles r
JOIN permissions p
    ON p.name IN (
        'Notas',
        'Frequência'
    )
WHERE r.name = 'Alunos'
ON CONFLICT (role_id, permission_id)
DO UPDATE SET
    access = EXCLUDED.access;


